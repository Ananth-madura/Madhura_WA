"use strict";
const fs=require("node:fs"),path=require("node:path"),crypto=require("node:crypto");
const root=path.resolve(__dirname,"../..");
const skip=new Set(["node_modules","build","dist","coverage",".git",".agents",".codex",".aws",".cache",".wwebjs_cache","whatsapp-sessions","uploads","logs","backups","scratch"]);
const source=/\.(?:js|jsx|cjs|mjs|ts|tsx|css|html|md|conf|service|timer|sh)$/;
function inventory(directory){
  const files=[];
  for(const entry of fs.readdirSync(directory,{withFileTypes:true})){
    if(entry.name.startsWith(".env")||entry.isSymbolicLink()||skip.has(entry.name))continue;
    const file=path.join(directory,entry.name);
    if(entry.isDirectory()){files.push(...inventory(file));continue;}
    if(!source.test(entry.name)&&!["package.json","vercel.json","schema.sql","Dockerfile","Dockerfile.cloud"].includes(entry.name))continue;
    const text=fs.readFileSync(file,"utf8"),count=regex=>(text.match(regex)||[]).length;
    files.push({file:path.relative(root,file).replace(/\\/g,"/"),bytes:Buffer.byteLength(text),lines:text.split("\n").length,sha256:crypto.createHash("sha256").update(text).digest("hex"),
      timers:count(/\bsetInterval\s*\(/g),syncFs:count(/\b(?:readFileSync|writeFileSync|statSync|readdirSync)\s*\(/g),selectStar:count(/SELECT\s+\*/gi),httpCalls:count(/\b(?:axios\.(?:get|post|put|patch|delete)|fetch)\s*\(/g),lazyImports:count(/\blazy\s*\(/g)});
  }
  return files;
}
function workload(){
  const organizations=200*5,employees=organizations*25,customerInteractions=employees*100;
  return {businessCustomers:200,organizations,employees,customerInteractions,messagesPerDay:{low:customerInteractions*20,high:customerInteractions*50},
    activeHours:8,averagePerSecond24h:{low:customerInteractions*20/86400,high:customerInteractions*50/86400},
    averagePerSecond8h:{low:customerInteractions*20/28800,high:customerInteractions*50/28800},
    peak5xPerSecond8h:{low:customerInteractions*100/28800,high:customerInteractions*250/28800}};
}
function main(){
  const files=[...inventory(path.join(root,"backend")),...inventory(path.join(root,"frontend"))].sort((a,b)=>a.file.localeCompare(b.file));
  const report={at:new Date().toISOString(),method:"Static source inventory and pattern counts; not exhaustive semantic certification. Secrets, runtime data, generated files, dependencies and symlinks excluded.",
    workload:workload(),sourceFiles:files.length,totalLines:files.reduce((total,row)=>total+row.lines,0),files};
  fs.writeFileSync(path.join(root,"capacity_audit.json"),JSON.stringify(report,null,2)+"\n");
  const rows=files.map(row=>`| [${row.file}](${row.file}) | ${row.lines} | ${row.timers} | ${row.syncFs} | ${row.selectStar} | ${row.httpCalls} |`);
  fs.writeFileSync(path.join(root,"capacity_file_audit.md"),`# Frontend/backend source inventory\n\n${report.method}\n\nGenerated by \`node backend/scripts/capacity-audit.js\`. Source files: ${files.length}; lines: ${report.totalLines}. Performance decisions and verification limits are in [capacity_report.md](capacity_report.md). Pattern counts identify review candidates; synchronous filesystem calls in CLI tools, for example, are not automatically runtime defects.\n\n| File | Lines | Interval timers | Sync filesystem calls | SELECT * | HTTP calls |\n|---|---:|---:|---:|---:|---:|\n${rows.join("\n")}\n`);
  console.log(JSON.stringify({sourceFiles:report.sourceFiles,totalLines:report.totalLines,workload:report.workload}));
}
if(require.main===module)main();
module.exports={workload,inventory};
