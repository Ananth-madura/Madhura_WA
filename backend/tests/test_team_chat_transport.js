"use strict";
const assert = require("node:assert/strict");
const { io: connect } = require("socket.io-client");
const { createHarness } = require("./helpers/teamChatHarness");

(async () => {
  const harness = await createHarness();
  const [arun, priya] = harness.users;
  let socket;
  let attacker;
  let expiring;
  try {
    socket = connect(harness.origin, { auth: { token: priya.token }, transports: ["websocket"], reconnection: false });
    await new Promise((resolve, reject) => { socket.once("connect", resolve); socket.once("connect_error", reject); });
    socket.emit("join", priya.id);
    await new Promise((resolve) => setTimeout(resolve, 50));
    attacker = connect(harness.origin, { auth: { token: arun.token }, transports: ["websocket"], reconnection: false });
    await new Promise((resolve, reject) => { attacker.once("connect", resolve); attacker.once("connect_error", reject); });
    attacker.emit("join", priya.id);
    await new Promise((resolve) => setTimeout(resolve, 50));
    assert.equal(harness.io.sockets.sockets.get(attacker.id).rooms.has(`user:${priya.id}`), false, "a socket cannot impersonate another participant room");
    attacker.disconnect();
    const direct = await harness.request(arun, "POST", "/direct", { userId: priya.id });
    assert.equal(direct.status, 200);
    const id = direct.data.channel.id;
    const messages = [];
    socket.on("team_chat_message", (event) => messages.push(event));
    const sent = await harness.request(arun, "POST", `/channels/${id}/messages`, { text: "Transport verification", clientId: "transport-1" });
    assert.equal(sent.status, 201);
    const replay = await harness.request(arun, "POST", `/channels/${id}/messages`, { text: "Transport verification", clientId: "transport-1" });
    assert.equal(replay.data.message.id, sent.data.message.id);
    await new Promise((resolve) => setTimeout(resolve, 100));
    assert.equal(messages.length, 1, "idempotent sends produce one recipient event");
    assert.equal(messages[0].tenantId, 1);
    const presence = await harness.request(arun, "GET", "/presence");
    assert.ok(presence.data.onlineUserIds.includes(priya.id));
    const sync = await harness.request(priya, "GET", `/channels/${id}/sync`);
    assert.equal(sync.status, 200);
    assert.equal(sync.data.messages.length, 1);
    await harness.request(arun, "PATCH", `/channels/${id}/messages/${sent.data.message.id}`, { text: "Updated while disconnected" });
    const edits = await harness.request(priya, "GET", `/channels/${id}/sync?after=${sync.data.cursor}`);
    assert.equal(edits.data.messages[0].body, "Updated while disconnected");
    await harness.request(priya, "POST", `/channels/${id}/read`);
    const readState = await harness.request(arun, "GET", `/channels/${id}/sync?after=${edits.data.cursor}`);
    assert.ok(readState.data.readers.some((reader) => Number(reader.userId) === priya.id && Number(reader.lastReadId) >= sent.data.message.id));
    await harness.request(arun, "DELETE", `/channels/${id}/messages/${sent.data.message.id}`);
    const deletion = await harness.request(priya, "GET", `/channels/${id}/sync?after=${edits.data.cursor}`);
    assert.equal(deletion.data.messages[0].isDeleted, true);
    const form = new FormData(); form.append("file", new Blob(["Retention attachment"], { type: "text/plain" }), "retention.txt");
    const upload = await fetch(`${harness.origin}/api/v2/team-chat/channels/${id}/attachments`, { method: "POST", headers: { Authorization: `Bearer ${arun.token}`, "x-tenant-id": "1" }, body: form });
    assert.equal(upload.status, 201); const uploaded = await upload.json();
    const fileMessage = await harness.request(arun, "POST", `/channels/${id}/messages`, { text: "File retention", clientId: "file-retention", attachmentId: uploaded.attachment.id });
    assert.equal(fileMessage.status, 201);
    await harness.q("UPDATE team_chat_messages SET created_at = '2020-01-01 00:00:00' WHERE id = ?", [fileMessage.data.message.id]);
    const fs = require('node:fs'); const path = require('node:path');
    const orphan = path.join(require('../config/runtimePaths').privateChatDir, 'tc_orphan_qa.txt');
    fs.writeFileSync(orphan, 'Abandoned test upload'); fs.utimesSync(orphan, new Date('2020-01-01'), new Date('2020-01-01'));
    await harness.q("INSERT INTO team_chat_audit_logs (tenant_id, actor_id, action, target_type, created_at) VALUES (1, ?, 'QA_RETENTION', 'settings', '2020-01-01 00:00:00')", [arun.id]);
    await require('../services/teamChat').purgeExpired();
    assert.equal(fs.existsSync(orphan), false);
    assert.equal((await harness.q("SELECT id FROM team_chat_audit_logs WHERE action = 'QA_RETENTION'")).length, 0);
    const expiredFile = await fetch(harness.origin + uploaded.attachment.fileUrl, { headers: { Authorization: `Bearer ${arun.token}`, "x-tenant-id": "1" } });
    assert.equal(expiredFile.status, 404);
    assert.equal((await harness.q("SELECT id FROM team_chat_attachments WHERE id = ?", [uploaded.attachment.id])).length, 0);
    await harness.q("UPDATE organization_memberships SET membership_status = 'suspended' WHERE tenant_id = 1 AND user_id = ?", [priya.id]);
    const blocked = await harness.request(priya, "GET", `/channels/${id}/messages`);
    assert.equal(blocked.status, 403);
    assert.equal((await harness.request(arun, "GET", "/presence")).data.onlineUserIds.includes(priya.id), false, "revoked members do not expose presence");
    const shortToken = require('jsonwebtoken').sign({ id: arun.id, role: 'employee', tenant_id: 1 }, process.env.JWT_SECRET, { expiresIn: '3s' });
    expiring = connect(harness.origin, { auth: { token: shortToken }, transports: ['websocket'], reconnection: false });
    await new Promise((resolve, reject) => { expiring.once('connect', resolve); expiring.once('connect_error', reject); });
    await new Promise((resolve, reject) => { const timeout = setTimeout(() => reject(new Error('Expired socket stayed connected')), 5000); expiring.once('disconnect', () => { clearTimeout(timeout); resolve(); }); });
    socket.disconnect();
    const service = require('../services/teamChat'); service.startRetentionSweep();
    const deadline = Date.now() + 3000;
    while (!service.retentionState().lastSweepAt && Date.now() < deadline) await new Promise((resolve) => setTimeout(resolve, 20));
    assert.ok(service.retentionState().lastSweepAt, "the background retention worker runs without an employee request");
    console.log("PASS: authenticated HTTP + Socket.IO delivery, idempotent events, persisted edit/delete recovery, membership revocation");
  } finally { socket?.disconnect(); attacker?.disconnect(); expiring?.disconnect(); await harness.close(); }
})().catch((error) => { console.error(error); process.exitCode = 1; });
