import assert from "node:assert/strict";
import fs from "node:fs";

const preferences = new Map();
globalThis.localStorage = { getItem: (key) => preferences.get(key) ?? null, setItem: (key, value) => preferences.set(key, String(value)), key: (index) => [...preferences.keys()][index], get length() { return preferences.size; } };
globalThis.window = {};
const source = fs.readFileSync(new URL("../../frontend/src/utils/teamChatIndexedDB.js", import.meta.url), "utf8");
const cache = await import(`data:text/javascript;base64,${Buffer.from(source).toString("base64")}`);
const identity = (tenant, user) => { localStorage.setItem("active_tenant_id", tenant); localStorage.setItem("user", JSON.stringify({ id: user })); };
identity(1, 1);
const oldMessage = { id: 1, clientId: "old", body: "device history", createdAt: "2026-01-01T00:00:00Z" };
await cache.writeCachedMessages(10, [oldMessage]);
await cache.saveCachedDraft(10, "unsent draft");
await cache.queueOutbox({ clientId: "operation", channelId: 10, text: "queued" });
await cache.writeCachedChannels([{ id: 10, name: "private" }]);
identity(2, 1);
assert.deepEqual(await cache.readCachedMessages(10), []);
assert.equal(await cache.getCachedDraft(10), "");
assert.deepEqual(await cache.readOutbox(), []);
assert.deepEqual(await cache.readCachedChannels(), []);
identity(1, 2);
assert.deepEqual(await cache.readOutbox(), []);
identity(1, 1);
assert.equal((await cache.readCachedMessages(10))[0].body, "device history");
assert.equal(await cache.getCachedDraft(10), "unsent draft");
assert.equal((await cache.readOutbox()).length, 1);
await cache.reconcileAuthorizedChannels([{ id: 10 }]);
assert.equal((await cache.readCachedMessages(10)).length, 1, "server expiry is not cache revocation");
await cache.reconcileAuthorizedChannels([]);
assert.deepEqual(await cache.readCachedMessages(10), []);
assert.equal(await cache.getCachedDraft(10), "");
assert.deepEqual(await cache.readOutbox(), []);
const merged = cache.mergeMessages([{ id: "local:1", clientId: "op", pending: true, createdAt: "2026-10-28T00:00:00Z" }], [{ id: 2, clientId: "op", createdAt: "2026-10-28T00:00:01Z", body: "confirmed" }]);
assert.equal(merged.length, 1);
assert.equal(merged[0].id, 2);
assert.equal(Boolean(merged[0].pending), false);
assert.equal(cache.mergeMessages(merged, [{ ...merged[0], isDeleted: true, body: "deleted" }])[0].isDeleted, true);
const bound = cache.scopedChatStorage(1, 1);
identity(2, 2);
await bound.writeCachedMessages(10, [oldMessage]);
assert.deepEqual(await cache.readCachedMessages(10), []);
assert.equal((await bound.readCachedMessages(10))[0].body, "device history", "delayed writes stay in their original scope");
assert.equal(cache.mergeMessages([{ id: 1, senderId: 1, clientId: "same" }, { id: 2, senderId: 2, clientId: "same" }]).length, 2, "other senders cannot collide with operation IDs");
assert.equal(cache.mergeMessages([{ id: 1, stateVersion: 3, body: "new" }], [{ id: 1, stateVersion: 2, body: "old" }])[0].body, "new");
await bound.applyDevicePolicy({ localCacheDays: 1, clearCacheOnLogout: true });
assert.deepEqual(await bound.readCachedMessages(10), [], "configured local retention is distinct from server retention");
await bound.writeCachedMessages(10, [{ ...oldMessage, createdAt: new Date().toISOString() }]);
const second = cache.scopedChatStorage(2, 1);
await second.applyDevicePolicy({ localCacheDays: 0, clearCacheOnLogout: false });
await second.writeCachedMessages(10, [oldMessage]);
await cache.clearChatCachesOnLogout(1);
assert.deepEqual(await bound.readCachedMessages(10), []);
assert.equal((await second.readCachedMessages(10)).length, 1, "logout honors each organization's retention policy");
console.log("PASS: fallback storage tenant/user isolation, drafts, outbox, revocation, retained history, canonical send reconciliation and deletion merge");
